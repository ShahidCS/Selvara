export interface Connection {
  id: string; provider: string; label: string; status: "Setting up" | "Pending approval" | "Connected" | "Disconnected";
  config: Config; sealedKey?: string; jwk?: string; externalId?: string;
  createdBy: string; createdById: string; createdAt: number; approvedBy?: string; connectedAt?: number;
  lastSyncAt?: number; lastOkAt?: number; health: "Never synced" | "Healthy" | "Degraded" | "Failing" | "Credential refused"; lastError?: string; counts: Record<string, number>; tests: string[];
  disconnectedBy?: string; disconnectReason?: string;
}
interface Run { id: string; conn: string; at: number; by: string; ok: boolean; error?: string; pass: number; fail: number; needs: number; counts: Record<string, number> }
const KIND = "integration.connect"; const TTL = 24 * 3600_000; const DUE = 24 * 3600_000; const GAP = 5 * 60_000;
const AI_APP = /\b(openai|chatgpt|gpt-?\d|anthropic|claude|copilot|gemini|bard|perplexity|midjourney|mistral|hugging ?face|jasper|otter\.?ai|cohere|deepl|cursor|codeium|tabnine|poe|character\.?ai|elevenlabs|runway|synthesia)\b/i;
const stamp = (ms: number) => new Date(ms).toISOString().slice(0, 16).replace("T", " ") + " UTC";
const envOf = (d: Deps): IntegrationEnv => d.intEnv ?? integrationEnv(process.env);
const testId = (conn: string, key: string) => `AT-${conn.replace(/\D/g, "")}-${key}`;

registerFourEyes(KIND, { mod: "integrations", apply: async (_d, t, ap: ApprovalRow, by) => {
  const rec = (await t.get<Connection>("integration", String(ap.payload.id))) ?? missing("Connection"); const c = rec!.data;
  if (c.status !== "Pending approval") invalid("This connection is no longer waiting for approval.");
  Object.assign(c, { status: "Connected", approvedBy: by, connectedAt: t.now, health: "Never synced" }); await t.update("integration", rec!.id, c, rec!.version);
  await t.audit("integration.connected", `${c.label} (${c.id}; approved by ${by}; requested by ${ap.requestedByName})`, "System");
} });

/** Writes a sync's results: automated tests (System), the account list, discovery, the run and the connection's health. */
async function record(d: Deps, t: WsTx, c: Connection, out: SyncOut | null, error: ProviderError | null, system: boolean) {
  const prov = providerOf(c.provider)!; let checks: Check[] = out?.checks ?? [];
  if (out && ["okta", "entra", "google"].includes(c.provider)) { // people who left the company in Selvara and are still active in the provider
    const gone = new Map((await d.dir.members(t.actor.tenantId, t.actor.id, "Removed")).map((m) => [m.email.toLowerCase(), m.person]));
    const still = out.accounts.filter((a) => a.status === "Active" && a.email && gone.has(a.email));
    checks = [...checks, { key: `${c.provider}-leavers`, name: `No ${prov.name} account of a person who left is still active`, logic: "Accounts of people removed from the company in Selvara are suspended or deleted in the provider.", result: still.length ? "Fail" : "Pass",
      items: still.length ? still.slice(0, 20).map((a) => ({ item: `${a.email}: left the company, account still active`, result: "Fail" })) : [{ item: `${gone.size} people who left checked`, result: "Pass" }], note: `${still.length} still active.` }];
  }
  const keys = new Set(checks.map((x) => x.key)); const ids = new Set(c.tests); const touched: string[] = [];
  const save = async (id: string, f: (x: Test) => void, fresh?: Test) => {
    const rec = await t.get<Test>("test", id); const before = rec?.data.result;
    const x: Test = rec?.data ?? fresh!; f(x);
    if (rec) await t.update("test", id, x, rec.version); else await t.insert("test", id, x);
    if (x.result !== before) await t.audit("test.result.recorded", `${id} ${x.name}: ${x.result} by System: ${(x.note ?? "").slice(0, 300)}`, "Control", true);
    touched.push(...x.controls); ids.add(id);
  };
  for (const ch of checks) {
    const id = testId(c.id, ch.key); const name = c.provider === "aws" ? `${ch.name} (${c.label})` : ch.name;
    await save(id, (x) => { Object.assign(x, { name, logic: ch.logic, result: ch.result, items: ch.items, note: ch.note, last: stamp(t.now) }); },
      { id, name, source: prov.name, controls: [], logic: ch.logic, result: ch.result, cadence: "Daily (integration)", last: stamp(t.now), items: ch.items, note: ch.note });
  }
  // a failed sync, or a check the provider no longer answers: never a stale Pass
  for (const id of [...ids].filter((x) => error || !keys.has(x.split("-").slice(2).join("-")))) {
    if (!(await t.get<Test>("test", id))) { ids.delete(id); continue; }
    await save(id, (x) => { x.result = "Needs data"; x.note = error ? `The last sync failed: ${error.message}` : "The provider no longer returns this check."; x.items = []; x.last = stamp(t.now); });
  }
  c.tests = [...ids];
  if (out) {
    const acc = await t.get<{ accounts: Account[] }>("integration-accounts", c.id); const data = { accounts: out.accounts.slice(0, 5000) };
    if (acc) await t.update("integration-accounts", c.id, data, acc.version); else await t.insert("integration-accounts", c.id, data);
    await discover(t, c, prov.name, out.apps);
  }
  const pass = checks.filter((x) => x.result === "Pass").length, fail = checks.filter((x) => x.result === "Fail").length, needs = checks.filter((x) => x.result === "Needs data").length;
  const runId = `SYNC-${await t.next("integration-run", 0)}`;
  await t.insert("integration-run", runId, { id: runId, conn: c.id, at: t.now, by: system ? "System" : t.actor.name, ok: !error, error: error?.message, pass, fail, needs, counts: out?.counts ?? {} } satisfies Run);
  const was = c.health;
  c.lastSyncAt = t.now; c.health = error ? (error.status === 401 || error.status === 403 ? "Credential refused" : "Failing") : needs ? "Degraded" : "Healthy";
  if (out) { c.lastOkAt = t.now; c.counts = out.counts; c.label = out.label; delete c.lastError; } else c.lastError = error?.message;
  await t.audit(error ? "integration.sync_failed" : "integration.synced", error ? `${c.label} (${c.id}): ${error.message}` : `${c.label} (${c.id}): ${pass} pass, ${fail} fail, ${needs} need data`, "System", system);
  if (error && was !== c.health) for (const m of await d.dir.members(t.actor.tenantId, t.actor.id, "Active")) if (m.role === "admin") await t.notify(m.userId, `Integration ${c.label.slice(0, 60)} could not sync: ${error.message.slice(0, 160)}`);
  await followTests(t, touched);
}
/** Applications people use: AI ones become discovered (shadow) AI, the rest are matched to vendors' "Discovered applications". */
async function discover(t: WsTx, c: Connection, source: string, apps: { name: string; users: number | null }[]) {
  const known = new Set([...(await t.list<{ name: string }>("ai-shadow")).map((x) => x.data.name.toLowerCase()), ...(await t.list<{ name: string }>("ai-system")).map((x) => x.data.name.toLowerCase())]);
  let found = 0;
  for (const a of apps.filter((x) => AI_APP.test(x.name)).slice(0, 50)) {
    if (known.has(a.name.toLowerCase())) continue; known.add(a.name.toLowerCase());
    const id = `SH-${String(await t.next("ai-shadow", 0)).padStart(2, "0")}`;
    await t.insert("ai-shadow", id, { id, name: a.name.slice(0, 120), found: `${source} (${c.label})`.slice(0, 120), where: c.provider === "github" ? "GitHub App on the organisation" : "Single sign-on or authorised app", data: a.users ? `${a.users} people` : "People's accounts", risk: "Unregistered AI" });
    found++;
  }
  if (found) await t.audit("ai.shadow.discovered", `${found} AI applications found by ${c.label}`, "AI governance", true);
  for (const v of await t.list<{ name: string; apps: { name: string; users: number | string; sanctioned: boolean; source?: string }[] }>("vendor")) {
    const n = v.data.name.toLowerCase(); if (n.length < 3) continue;
    const hits = apps.filter((a) => a.name.toLowerCase().includes(n)).slice(0, 20).map((a) => ({ name: a.name, users: a.users ?? "—", sanctioned: true, source: c.id }));
    const keep = (v.data.apps ?? []).filter((a) => a.source !== c.id);
    const next = [...keep, ...hits];
    if (JSON.stringify(next) !== JSON.stringify(v.data.apps ?? [])) { v.data.apps = next; await t.update("vendor", v.id, v.data, v.version); }
  }
}

export function integrationRoutes(h: WsHelpers) {
  const tx = <T,>(d: Deps, c: { actor: Actor }, w: (t: WsTx) => Promise<T>) => d.ws.tx(c.actor, d.now(), w);
  const adminOnly = (me: Actor) => refuse(me.role === "admin" ? null : "Only an admin can change integrations.");
  const route = (fn: Parameters<typeof wsRoute>[2]) => wsRoute(h, "integrations", async (d, r, c) => { adminOnly(c.actor); return fn(d, r, c); });
  const load = async (t: WsTx, id: unknown) => (await t.get<Connection>("integration", str(id, 20))) ?? missing("Connection");
  const ctxOf = (d: Deps) => ({ net: d.net ?? httpsNet, env: envOf(d), now: d.now(), secret: (s: string) => unseal(d.secret, s) });

  /** One sync of one connection: read outside any transaction, then record. */
  async function syncOne(d: Deps, actor: Actor, id: string, system: boolean) {
    const c0 = await d.ws.tx(actor, d.now(), async (t) => {
      const c = (await load(t, id)).data; if (c.status !== "Connected") invalid("Only a connected integration syncs.");
      if (!system && c.lastSyncAt && d.now() - c.lastSyncAt < GAP) invalid("This integration synced less than 5 minutes ago. Try again shortly.");
      return c;
    });
    let out: SyncOut | null = null; let error: ProviderError | null = null;
    try { out = await providerOf(c0.provider)!.sync(ctxOf(d), { ...c0.config, externalId: c0.externalId ?? "", privateKey: c0.sealedKey ?? "", kid: c0.config.kid ?? "" }); }
    catch (e) { error = e instanceof ProviderError ? e : new ProviderError("The provider's answer could not be read."); }
    return d.ws.tx(actor, d.now(), async (t) => {
      const rec = await load(t, id); if (rec.data.status !== "Connected") invalid("The integration was disconnected during the sync.");
      await record(d, t, rec.data, out, error, system);
      await t.update("integration", rec.id, rec.data, rec.version);
      return { ok: !error, error: error?.message, health: rec.data.health };
    });
  }

  const data = route(async (d, _r, c) => ok(await tx(d, c, async (t) => {
    await sweepApprovals(t, [KIND]);
    const env = envOf(d); const pend = await pendingOf(t, [KIND]); const site = d.site.origin;
    const members = await d.dir.members(c.actor.tenantId, c.actor.id); const byEmail = new Map(members.map((m) => [m.email.toLowerCase(), m]));
    const names = new Map(members.map((m) => [m.userId, m.person]));
    const conns = (await t.list<Connection>("integration")).map((x) => x.data).filter((x) => x.status !== "Disconnected" || x.lastSyncAt || x.connectedAt);
    const tests = (await t.list<Test>("test")).map((x) => x.data);
    const out = [];
    for (const x of conns) {
      const p = providerOf(x.provider)!; const accts = (await t.get<{ accounts: Account[] }>("integration-accounts", x.id))?.data.accounts ?? [];
      const pending = pend.find((a) => a.subject === x.id);
      out.push({
        id: x.id, provider: x.provider, name: p.name, type: p.type, scope: p.scope, label: x.label, status: pending ? "Pending approval" : x.status === "Pending approval" ? "Not approved" : x.status, approvalId: pending?.id,
        config: x.config, externalId: x.externalId, jwk: x.jwk, instructions: p.instructions(env, { ...x.config, externalId: x.externalId, jwk: x.jwk }, site), fields: p.fields.map((f) => ({ key: f.key, label: f.label, help: f.help, example: f.example })),
        createdBy: x.createdBy, approvedBy: x.approvedBy, connected: x.connectedAt ? stamp(x.connectedAt) : "", lastSync: x.lastSyncAt ? stamp(x.lastSyncAt) : "never", health: x.health, lastError: x.lastError, counts: x.counts,
        due: x.status === "Connected" && (!x.lastSyncAt || d.now() - x.lastSyncAt >= DUE), disconnectedBy: x.disconnectedBy, disconnectReason: x.disconnectReason,
        checks: tests.filter((y) => x.tests.includes(y.id)).map((y) => ({ id: y.id, name: y.name, result: y.result, note: y.note, items: y.items, controls: y.controls, last: y.last })),
        accounts: accts.slice(0, 2000).map((a) => { const m = a.email ? byEmail.get(a.email) : undefined; return { ...a, member: m ? `${m.person}${m.status !== "Active" ? ` (${m.status.toLowerCase()} in Selvara)` : ""}` : null }; }),
      });
    }
    return {
      providers: PROVIDERS.map((p) => ({ id: p.id, name: p.name, type: p.type, scope: p.scope, ready: p.ready(env), active: conns.some((x) => x.provider === p.id && x.status !== "Disconnected") })),
      connections: out.reverse(),
      runs: (await t.list<Run>("integration-run")).map((x) => x.data).sort((a, b) => b.at - a.at).slice(0, 50).map((x) => ({ ...x, when: stamp(x.at) })),
      approvals: await approvalsView(t, [KIND], names),
    };
  })));
  /** Starts a connection: Selvara's own per-company values first (AWS external id, Okta key pair), so the admin can set up the provider side. */
  const start = route(async (d, r, c) => {
    const p = providerOf(str(r.path[2], 10)) ?? missing("Integration"); refuse(p!.ready(envOf(d)));
    return tx(d, c, async (t) => {
      const all = (await t.list<Connection>("integration")).map((x) => x.data);
      if (p!.id !== "aws" && all.some((x) => x.provider === p!.id && x.status !== "Disconnected")) invalid(`${p!.name} is already connected or being set up.`);
      if (all.filter((x) => x.status !== "Disconnected").length >= 20) invalid("A company can have at most 20 integrations.");
      const id = `INT-${await t.next("integration", 0)}`; const x: Connection = { id, provider: p!.id, label: p!.name, status: "Setting up", config: {}, createdBy: c.actor.name, createdById: c.actor.id, createdAt: t.now, health: "Never synced", counts: {}, tests: [] };
      if (p!.id === "aws") x.externalId = `selvara-${randomBytes(16).toString("hex")}`;
      if (p!.id === "okta") { const k = newKeyPair(); x.sealedKey = seal(d.secret, k.privateKeyPem); x.jwk = JSON.stringify(k.jwk); x.config.kid = k.kid; }
      await t.insert("integration", id, x); await t.audit("integration.setup_started", `${p!.name} (${id})`, "System");
      return ok({ id });
    });
  });
  /** The admin entered the identifiers: one small read proves they work, then a second admin approves the connection. */
  const connect = route(async (d, r, c) => {
    const x = await tx(d, c, async (t) => (await load(t, r.path[2])).data);
    if (x.status !== "Setting up" && x.status !== "Pending approval") invalid("This connection is not being set up.");
    const p = providerOf(x.provider)!; refuse(p.ready(envOf(d)));
    const cfg: Config = { ...x.config };
    for (const f of p.fields) { const v = txt((r.body.fields as Record<string, unknown> | undefined)?.[f.key], 200); if (!f.pattern.test(v)) invalid(`${f.label}: enter a value like ${f.example}.`); cfg[f.key] = v; }
    let label: string;
    try { label = await p.test(ctxOf(d), { ...cfg, externalId: x.externalId ?? "", privateKey: x.sealedKey ?? "" }); }
    catch (e) {
      const why = e instanceof ProviderError ? e.message : "The provider's answer could not be read.";
      await tx(d, c, (t) => t.audit("integration.connect_failed", `${p.name} (${x.id}): ${why}`, "System"));
      return invalid(`The connection test failed. ${why}`);
    }
    return tx(d, c, async (t) => {
      const rec = await load(t, x.id); const y = rec.data;
      if ((await pendingOf(t, [KIND])).some((a) => a.subject === y.id)) invalid("This connection is already waiting for approval.");
      Object.assign(y, { config: cfg, label: label.slice(0, 120), status: "Pending approval" }); await t.update("integration", rec.id, y, rec.version);
      await t.request({ kind: KIND, title: `Connect ${label.slice(0, 120)} (read-only; brings account data into Selvara)`, subject: y.id, payload: { id: y.id }, needs: 1, approverRoles: ["admin"], forbid: [], ttlMs: TTL });
      await t.audit("integration.connect_requested", `${label} (${y.id}); connection test passed`, "System");
      return ok({ id: y.id, label, pending: true });
    });
  });
  const sync = route(async (d, r, c) => ok(await syncOne(d, c.actor, str(r.path[2], 20), false)));
  /** Due syncs (more than a day old) when an admin opens the module: at most two per call, attributed to System. */
  const syncDue = route(async (d, _r, c) => {
    const due = await tx(d, c, async (t) => (await t.list<Connection>("integration")).map((x) => x.data).filter((x) => x.status === "Connected" && (!x.lastSyncAt || d.now() - x.lastSyncAt >= DUE)).slice(0, 2).map((x) => x.id));
    const done = []; for (const id of due) done.push(await syncOne(d, c.actor, id, true).catch(() => null));
    return ok({ synced: done.filter(Boolean).length });
  });
  const syncAll = route(async (d, _r, c) => {
    const ids = await tx(d, c, async (t) => (await t.list<Connection>("integration")).map((x) => x.data).filter((x) => x.status === "Connected" && (!x.lastSyncAt || d.now() - x.lastSyncAt >= GAP)).slice(0, 5).map((x) => x.id));
    let okN = 0; for (const id of ids) if ((await syncOne(d, c.actor, id, false).catch(() => null))?.ok) okN++;
    await tx(d, c, (t) => t.audit("integrations.synced", `${okN} of ${ids.length} connections synced`, "System"));
    return ok({ synced: okN, of: ids.length });
  });
  /** Disconnecting: a reason; the sealed key and the account list are erased; the connector's tests need data again. */
  const disconnect = route(async (d, r, c) => {
    const reason = txt(r.body.reason, 300); if (reason.length < 10) invalid("Give a reason of at least 10 characters.");
    return tx(d, c, async (t) => {
      const rec = await load(t, r.path[2]); const x = rec.data;
      if (x.status === "Disconnected") invalid("Already disconnected.");
      for (const a of (await pendingOf(t, [KIND])).filter((a) => a.subject === x.id)) { await t.setApproval(a.id, "Withdrawn"); await t.audit(`approval.${KIND}.withdrawn`, `${a.title} (${a.id}); disconnected`, "Approval"); }
      const touched: string[] = [];
      for (const id of x.tests) {
        const tr = await t.get<Test>("test", id); if (!tr) continue;
        Object.assign(tr.data, { result: "Needs data", items: [], note: `Disconnected by ${c.actor.name}: ${reason}`, last: stamp(t.now) }); await t.update("test", id, tr.data, tr.version);
        await t.audit("test.result.recorded", `${id} ${tr.data.name}: Needs data by System: integration disconnected`, "Control", true); touched.push(...tr.data.controls);
      }
      const acc = await t.get("integration-accounts", x.id); if (acc) await t.remove("integration-accounts", x.id, acc.version);
      delete x.sealedKey; Object.assign(x, { status: "Disconnected", disconnectedBy: c.actor.name, disconnectReason: reason, health: "Never synced" });
      await t.update("integration", rec.id, x, rec.version);
      await t.audit("integration.disconnected", `${x.label} (${x.id}): ${reason}; account data erased`, "System");
      await followTests(t, touched);
      return ok({ id: x.id, provider: x.provider });
    });
  });
  /** Links an automated test to a control (or removes the link): the control then follows the test's result. */
  const link = route(async (d, r, c) => tx(d, c, async (t) => {
    const tr = (await t.get<Test>("test", str(r.path[3], 60))) ?? missing("Test"); if (!tr!.id.startsWith("AT-")) invalid("Only an integration's test is linked here.");
    const ctrl = str(r.body.controlId, 40); if (!(await t.get("control", ctrl))) invalid("Choose a control from the list.");
    const on = r.body.on !== false; const has = tr!.data.controls.includes(ctrl);
    if (on === has) invalid(on ? "Already linked." : "Not linked.");
    tr!.data.controls = on ? [...tr!.data.controls, ctrl] : tr!.data.controls.filter((x) => x !== ctrl); await t.update("test", tr!.id, tr!.data, tr!.version);
    await t.audit(on ? "test.control.linked" : "test.control.unlinked", `${tr!.id} ${tr!.data.name} ↔ ${ctrl}`, "Control");
    await followTests(t, [ctrl]);
    return ok({ ok: true });
  }));
  return {
    "GET ws/data/integrations": data, "POST ws/integrations/sync-all": syncAll, "POST ws/integrations/sync-due": syncDue, "POST ws/integrations/checks/:id/link": link,
    "POST ws/integrations/:provider/start": start, "POST ws/integrations/:id/connect": connect, "POST ws/integrations/:id/sync": sync, "POST ws/integrations/:id/disconnect": disconnect,
  };
}
