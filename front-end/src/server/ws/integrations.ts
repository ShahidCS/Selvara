/* Server-only. Integrations on the server (production programme group 7; inventory group 7). Company admins connect the read-only connectors
   the owner chose: GitHub, AWS, Okta, Microsoft Entra ID and Google Workspace (server/integrations/providers.ts). Decisions for production:
   - The demonstration's seven sample connectors do not exist in production; only these five, each needing the platform credentials the owner
     sets (Vercel variables) and identifiers a company admin enters. Okta's private key is generated by Selvara per company and kept sealed;
     AWS's external id is generated per company. No password or token of the company's is ever entered or stored.
   - Connecting is tested with one small read first, then approved by a second admin (`integration.connect`): it brings employee data in.
     Disconnecting is immediate, needs a reason, erases the sealed key and the account list, and turns the connector's tests to Needs data.
   - A sync reads what the checks need and records automated tests in Controls (results recorded by System, the same way a person records
     one, so linked controls follow their tests and `control.failed` webhooks fire). A failed sync never leaves a stale Pass. Accounts are
     matched to members by email; an account of someone who left the company in Selvara and is still active in the provider fails a check.
     Applications people use feed AI discovery (shadow AI) and the Vendors register (discovered applications).
   - Syncs run on demand and, once a day, when an admin opens the module (there is no scheduler without a Vercel cron, which needs the owner's
     approval). One sync per connection every 5 minutes. Provider calls run outside any database transaction.
   - GitHub, Entra ID and Google trust one Selvara app for every customer, so a tenant is bound to a company only through a sign-in by one of
     its people (the identifier comes from the provider's answer, never from what an admin types), and one provider tenant can be connected
     to one Selvara company at a time (a platform-wide binding). AWS roles must require the company's external id; Okta keys are per company.
   - A sync has a time budget and a lock; a failed sync keeps a known Fail (only a Pass drops to Needs data). Automated tests cannot be
     overwritten by hand in Controls, and a Pass not refreshed for 3 days needs data again.
   - Everything is in the company's own audit log, never a secret or token. */
