/* Workspace billing stubs (subscription, payment method, plan change, invoices). Mock mode mutates in-memory SUBSCRIPTION; the caller does wsLog / toast.
 * The real API MUST: authorize billing changes server-side (billing admin), take card data ONLY via the payment provider's hosted fields
 * (this UI never handles a PAN/CVC; it edits brand/last4/expiry display values only), and generate invoices server-side. */
import seed from "@/data/billingWsSeed.json";
import plans from "@/data/plans.json";
import { modAllowed } from "@/lib/rbac";
import { apiFetch, viaApi } from "./http";

export interface Plan { seats: number; price: number; modules: string[]; limits: { screenings: number; idv: number; storageGB: number } }
export interface Invoice { id: string; date: string; period: string; amount: number; status: string }
export interface Subscription {
  plan: string; cycle: string; seatsUsed: number; seatLimit: number; amount: number; nextInvoice: string;
  payment: { brand: string; last4: string; exp: string; name: string };
  usage: { k: string; used: number; limit: number; unit: string }[]; invoices: Invoice[];
}
export const PLANS: Record<string, Plan> = JSON.parse(JSON.stringify(plans.PLANS));
export const CARD_BRANDS = ["Visa", "Mastercard", "Amex"];
export const SUBSCRIPTION: Subscription = JSON.parse(JSON.stringify(seed.SUBSCRIPTION));
const post = <T,>(path: string, body: unknown) => apiFetch<T>(path, { method: "POST", body: JSON.stringify(body) });

/** UI gate only. The source had no per-action gate (module access only); deny by default = same rule as module access. */
export const billingCanManage = (roleId: string) => modAllowed(roleId, "ws", "billingws");

/** Prototype: billwsSavePayment (blank fields keep the old value; last4 = digits only, max 4). */
export function savePayment(input: { brand: string; last4: string; exp: string; name: string }) {
  return viaApi<Subscription["payment"]>(() => {
    const p = SUBSCRIPTION.payment;
    p.brand = CARD_BRANDS.includes(input.brand) ? input.brand : p.brand;
    p.last4 = (input.last4 || "").replace(/\D/g, "").slice(0, 4) || p.last4;
    p.exp = input.exp.trim() || p.exp;
    p.name = input.name.trim() || p.name;
    return p;
  }, () => post<Subscription["payment"]>("/billing/payment-method", input));
}
/** Prototype: billwsDoChangePlan. Returns null when the plan is unknown, `{ changed:false }` when it is already the current plan. */
export function changePlan(plan: string) {
  return viaApi<{ changed: boolean; plan: string } | null>(() => {
    if (!Object.prototype.hasOwnProperty.call(PLANS, plan)) return null;
    const s = SUBSCRIPTION; if (plan === s.plan) return { changed: false, plan };
    s.plan = plan; s.seatLimit = PLANS[plan].seats; s.amount = PLANS[plan].price * (s.cycle === "Annual" ? 12 : 1);
    return { changed: true, plan };
  }, () => post<{ changed: boolean; plan: string } | null>("/billing/plan", { plan }));
}
/** Prototype: billwsDownload text. Synthetic sample, not a tax invoice. */
export function invoiceText(iv: Invoice, money: (n: number) => string): string {
  const s = SUBSCRIPTION;
  return ["SELVARA — INVOICE (synthetic sample)", "", "Invoice: " + iv.id, "Date: " + iv.date, "Period: " + iv.period, "Plan: " + s.plan + " (" + s.cycle + ")", "Seats: " + s.seatsUsed + " / " + s.seatLimit, "", "Amount due: " + money(iv.amount), "Status: " + iv.status, "", "Generated by the Assurance prototype. Not a valid tax invoice."].join("\n");
}
export const findInvoice = (id: string) => SUBSCRIPTION.invoices.find((x) => x.id === id);
